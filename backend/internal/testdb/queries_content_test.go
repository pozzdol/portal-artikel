	// --- videos
	videos, err := q.ListPublishedVideos(ctx, dbgen.ListPublishedVideosParams{Limit: 10})
	require.NoError(t, err)
	assert.Len(t, videos, 3)
	assert.True(t, videos[0].IsFeatured)
	others, err := q.ListPublishedVideos(ctx, dbgen.ListPublishedVideosParams{ExcludeID: &videos[0].ID, Limit: 6})
