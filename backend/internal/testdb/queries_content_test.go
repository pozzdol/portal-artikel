	alAdmin, err := q.ListAlumniAdmin(ctx, dbgen.ListAlumniAdminParams{Limit: 50})
	require.NoError(t, err)
	n, err = q.CountAlumniAdmin(ctx, dbgen.CountAlumniAdminParams{})
	require.NoError(t, err)
	assert.EqualValues(t, len(alAdmin), n)
	_, err = q.GetAlumni(ctx, al.ID)
	require.NoError(t, err)
	_, err = q.ListPublishedAlumniForSitemap(ctx)
	require.NoError(t, err)
	alumniCards, err := h.AlumniCards(ctx, alumni)
	require.NoError(t, err)
	assert.Equal(t, "/tokoh/"+alumni[0].Slug, alumniCards[0].URL)
